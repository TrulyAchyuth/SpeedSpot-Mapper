"""Generate the India illustration used on the homepage and in empty states.

It is drawn from the same LGD state boundaries as the map (frontend/static/geo/states.geojson),
so the outline matches India's official depiction. Output: frontend/static/assets/india-states.svg

Run:  python scripts/build_illustrations.py
"""
import json
import math
from pathlib import Path

import shapely
from shapely.geometry import shape

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "frontend" / "static" / "geo" / "states.geojson"
TARGET = ROOT / "frontend" / "static" / "assets" / "india-states.svg"

TOLERANCE = 0.06        # degrees — plenty for a ~500 px illustration
WIDTH = 600             # SVG units
MIN_AREA = 0.02         # drop tiny islands (sq. degrees) except Andaman & Nicobar / Lakshadweep groups
COS = math.cos(math.radians(22))  # simple equirectangular projection centred on India


def main():
    features = json.loads(SOURCE.read_text())["features"]
    geoms = [(f["properties"]["code"], shapely.make_valid(shape(f["geometry"])).simplify(TOLERANCE)) for f in features]
    west, south, east, north = shapely.union_all([g for _, g in geoms]).bounds
    scale = WIDTH / ((east - west) * COS)
    height = (north - south) * scale

    def project(x, y):
        return (x - west) * COS * scale, (north - y) * scale

    def polygons(geom):
        """All polygons, however deeply nested (repairs can yield GeometryCollections of MultiPolygons)."""
        if geom.geom_type == "Polygon":
            yield geom
        for part in getattr(geom, "geoms", []):
            yield from polygons(part)

    def path(geom):
        parts = []
        for poly in polygons(geom):
            if poly.area < MIN_AREA and poly.bounds[0] < 90 and poly.bounds[1] > 13:
                continue  # skip slivers on the mainland, keep island groups
            points = [project(x, y) for x, y in poly.exterior.coords]
            parts.append("M" + "L".join(f"{px:.1f},{py:.1f}" for px, py in points) + "Z")
        return "".join(parts)

    paths = "\n".join(f'    <path d="{path(g)}"/>' for code, g in geoms if path(g))
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {height:.0f}" role="img" aria-label="Map of India">
  <!-- Generated by scripts/build_illustrations.py from LGD state boundaries. -->
  <g fill="#DCE9DF" stroke="#FFFFFF" stroke-width="1.2" stroke-linejoin="round">
{paths}
  </g>
</svg>
'''
    TARGET.write_text(svg)
    print(f"{TARGET.relative_to(ROOT)}: {len(svg) / 1024:.0f} KB, viewBox {WIDTH}×{height:.0f}")


if __name__ == "__main__":
    main()
