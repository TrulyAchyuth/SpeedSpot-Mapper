"""Build SpeedSpot's boundary and place files from official open data.

Inputs (downloaded into data/raw/, git-ignored — see docs/GEOSPATIAL.md §3):
  LGD_States.geojson, LGD_Districts.geojson   Local Government Directory boundaries
                                              (republished by bharatlas.com, CC0-1.0 / CC-BY-4.0)
  cities15000.zip                             GeoNames populated places (CC-BY 4.0)

Outputs (committed):
  frontend/static/geo/states.geojson          simplified, for the national view
  frontend/static/geo/districts/<STATE>.geojson  per-state districts, loaded on demand
  backend/reference/india_boundaries_index.json  state bboxes + district list (for the DB)
  backend/reference/india_cities.json            cities with their district

Run:  python scripts/build_boundaries.py
"""
import csv
import io
import json
import sys
import zipfile
from pathlib import Path

import numpy as np
import shapely
from shapely.geometry import Point, mapping, shape
from shapely.strtree import STRtree

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
GEO_OUT = ROOT / "frontend" / "static" / "geo"
REF = ROOT / "backend" / "reference"

STATE_TOLERANCE = 0.005     # degrees (~550 m): invisible at national zoom levels
DISTRICT_TOLERANCE = 0.0008  # degrees (~90 m): fine at district/city zoom, also used for lookups
CITY_FEATURE_CODES = {"PPL", "PPLA", "PPLA2", "PPLA3", "PPLA4", "PPLC"}  # excludes PPLX (city sections)


def simplify(geom, tolerance, decimals=4):
    geom = shapely.make_valid(geom).simplify(tolerance, preserve_topology=True)
    return shapely.transform(geom, lambda xy: np.round(xy, decimals))


def bbox(geom):
    west, south, east, north = geom.bounds
    return [round(south, 4), round(west, 4), round(north, 4), round(east, 4)]


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, separators=(",", ":"), ensure_ascii=False), encoding="utf-8")


def main():
    reference = json.loads((REF / "india_states_uts.json").read_text(encoding="utf-8"))
    by_lgd = {s["lgd_code"]: s for s in reference["states"]}

    # ---- States ----
    raw_states = json.loads((RAW / "LGD_States.geojson").read_text(encoding="utf-8"))["features"]
    state_features, state_bounds = [], {}
    for feature in raw_states:
        state = by_lgd.get(str(feature["properties"]["State_LGD"]))
        if state is None:
            sys.exit(f"Unmatched state in boundary file: {feature['properties']}")
        geom = shape(feature["geometry"])
        state_bounds[state["code"]] = bbox(geom)
        state_features.append({
            "type": "Feature",
            "properties": {"code": state["code"], "name": state["name"]},
            "geometry": mapping(simplify(geom, STATE_TOLERANCE, 3)),
        })
    if len(state_features) != 36:
        sys.exit(f"Expected 36 states/UTs, found {len(state_features)}")
    write_json(GEO_OUT / "states.geojson", {"type": "FeatureCollection", "features": state_features})

    # ---- Districts ----
    raw_districts = json.loads((RAW / "LGD_Districts.geojson").read_text(encoding="utf-8"))["features"]
    districts, per_state, geoms = [], {}, []
    for feature in raw_districts:
        props = feature["properties"]
        state = by_lgd.get(str(props["state_lgd"]))
        if state is None:
            sys.exit(f"District with unknown state: {props}")
        # Two districts (Muzaffarabad, Mirpur) are part of India's official map but have
        # no LGD code; they fall back to their Census 2011 district code.
        lgd = str(props["dist_lgd"]) if props["dist_lgd"] else None
        code = f"{state['code']}-D{lgd}" if lgd else f"{state['code']}-X{props['dtcode11']}"
        geom = simplify(shape(feature["geometry"]), DISTRICT_TOLERANCE)
        name = (props.get("dtname") or props.get("Dist")).strip()
        districts.append({"code": code, "name": name, "lgd_code": lgd,
                          "state_code": state["code"], "bbox": bbox(geom)})
        geoms.append((code, state["code"], geom))
        per_state.setdefault(state["code"], []).append({
            "type": "Feature",
            "properties": {"code": code, "name": name},
            "geometry": mapping(geom),
        })
    codes = [d["code"] for d in districts]
    if len(set(codes)) != len(codes):
        sys.exit("Duplicate district codes")
    for state_code, features in per_state.items():
        write_json(GEO_OUT / "districts" / f"{state_code}.geojson",
                   {"type": "FeatureCollection", "features": features})

    write_json(REF / "india_boundaries_index.json", {
        "_about": "Generated by scripts/build_boundaries.py from LGD boundaries (via bharatlas.com, "
                  "CC0-1.0 / CC-BY-4.0). bbox = [south, west, north, east].",
        "states": state_bounds,
        "districts": sorted(districts, key=lambda d: d["code"]),
    })

    # ---- Cities (GeoNames) ----
    tree = STRtree([g for _, _, g in geoms])
    cities = []
    with zipfile.ZipFile(RAW / "cities15000.zip") as zf:
        text = io.TextIOWrapper(zf.open("cities15000.txt"), encoding="utf-8")
        for row in csv.reader(text, delimiter="\t", quoting=csv.QUOTE_NONE):
            if row[8] != "IN" or row[7] not in CITY_FEATURE_CODES:
                continue
            lat, lng = float(row[4]), float(row[5])
            point = Point(lng, lat)
            hits = [i for i in tree.query(point) if geoms[i][2].covers(point)]
            if not hits:
                nearest = tree.nearest(point)
                if geoms[nearest][2].distance(point) > 0.05:
                    continue  # offshore or outside India's boundary
                hits = [nearest]
            district_code, state_code, _ = geoms[hits[0]]
            cities.append({"code": f"{state_code}-C{row[0]}", "name": row[1], "lat": round(lat, 4),
                           "lng": round(lng, 4), "population": int(row[14] or 0),
                           "district_code": district_code, "state_code": state_code})

    write_json(REF / "india_cities.json", {
        "_about": "Generated from GeoNames cities15000 (CC-BY 4.0, geonames.org). Populated places "
                  "with 15,000+ people, assigned to LGD districts by point-in-polygon.",
        "cities": sorted(cities, key=lambda c: -c["population"]),
    })

    sizes = {p.name: p.stat().st_size for p in [GEO_OUT / "states.geojson"]}
    district_bytes = sum(p.stat().st_size for p in (GEO_OUT / "districts").glob("*.geojson"))
    print(f"states: {len(state_features)}  districts: {len(districts)}  cities: {len(cities)}")
    print(f"states.geojson: {sizes['states.geojson'] / 1024:.0f} KB; "
          f"district files total: {district_bytes / 1024:.0f} KB "
          f"(largest {max(p.stat().st_size for p in (GEO_OUT / 'districts').glob('*.geojson')) / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
